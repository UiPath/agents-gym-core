import json
from collections.abc import Iterator
from pathlib import Path

import pytest
import yaml
from uipath.eval.models.evaluation_set import EvaluationSet

from agents_gym_core.hydra_agent.core_agent_registry import CoreAgentRegistry
from agents_gym_core.hydra_agent.evaluation_loader import EvaluationLoader, LabelledEvaluationSet
from agents_gym_core.loops.nodes import create_messages
from agents_gym_core.models.utils import LLM_BACKEND_ENV
from agents_gym_core.utils.gym_types import Agent

AGENTS = Path(__file__).resolve().parents[1] / "src" / "agents_gym_core" / "agents"
PAPER_AGENTS = [
    "claim_history",
    "customer_support_triage_agent",
    "meeting_management",
    "product_questions_agent",
    "sql",
    "hotpotqa",
    "hover",
    "aime_2025_agent",
    "livebench_math",
    "ifbench",
    "papillon",
]


GENERATED = {"hotpotqa", "hover", "aime_2025_agent", "livebench_math", "ifbench", "papillon"}


def _require_data(agent: str) -> None:
    """Public-benchmark splits are generated by ``gym init`` (gitignored); skip until they exist."""
    if agent in GENERATED and not any(
        (AGENTS / agent / "evaluations" / "eval-sets").glob("*.json")
    ):
        pytest.skip(f"{agent}: generated splits missing; run `uv run gym init {agent}`")


def _versions(agent: str) -> dict[str, dict]:
    return yaml.safe_load((AGENTS / agent / "versions.yaml").read_text()) or {}


def _expected(agent: str, ref: str) -> str:
    """A ``core::`` reference names a file; anything else is the prompt text itself."""
    if ref.startswith("core::"):
        return (AGENTS / agent / ref.removeprefix("core::")).read_text()
    return ref


CASES = [(agent, version) for agent in PAPER_AGENTS for version in _versions(agent)]


@pytest.fixture(scope="module")
def registry() -> Iterator[CoreAgentRegistry]:
    # Loading some agents builds their tools' models (e.g. the SQL query checker); the
    # public backend with a dummy key builds them offline without gateway credentials.
    with pytest.MonkeyPatch.context() as env:
        env.setenv(LLM_BACKEND_ENV, "langchain")
        env.setenv("OPENAI_API_KEY", "sk-test")
        env.delenv("AZURE_OPENAI_API_KEY", raising=False)
        yield CoreAgentRegistry()


_NO_EVAL_SET = LabelledEvaluationSet(EvaluationSet(id="none", name="none", evaluations=[]))


def _require_demos(agent: str, version: str) -> None:
    """Demos that quote benchmark text are written by ``gym init`` (gitignored); skip until
    they exist."""
    spec = (_versions(agent).get(version) or {}).get("agent") or {}
    for ref in (spec.get("signature_demos") or {}).values():
        if not (AGENTS / agent / ref.removeprefix("core::")).exists():
            pytest.skip(f"{agent}:{version}: {ref} missing; run `uv run gym init {agent}`")


def _load_prompts(registry: CoreAgentRegistry, agent: str, version: str) -> Agent:
    """Load a version without reading its eval sets, which may not be generated yet."""
    _require_demos(agent, version)
    with pytest.MonkeyPatch.context() as patch:
        patch.setattr(
            EvaluationLoader, "load_evaluation_set", staticmethod(lambda *_: _NO_EVAL_SET)
        )
        return registry.get_agent(agent, version)


@pytest.mark.parametrize(("agent", "version"), CASES, ids=[f"{a}:{v}" for a, v in CASES])
def test_version_loads_the_prompts_it_names(
    registry: CoreAgentRegistry, agent: str, version: str
) -> None:
    spec = (_versions(agent)[version] or {}).get("agent") or {}
    loaded = _load_prompts(registry, agent, version)

    for field in ("system_prompt", "user_prompt"):
        if field in spec:
            assert getattr(loaded, field).strip() == _expected(agent, spec[field]).strip(), field
    for module, ref in (spec.get("signature_prompts") or {}).items():
        assert loaded.signature_prompts[module].strip() == _expected(agent, ref).strip(), module


def test_every_paper_agent_has_the_gpt5_optimized_versions() -> None:
    for agent in PAPER_AGENTS:
        assert {"reapo__gpt-5-test", "gepa__gpt-5-test"} <= set(_versions(agent)), agent


LOCK = Path(__file__).resolve().parent / "data" / "paper_prompts_sha256.json"
LOCKED: dict[str, dict[str, dict]] = json.loads(LOCK.read_text()) if LOCK.exists() else {}
LOCK_CASES = [(agent, version) for agent in LOCKED for version in LOCKED[agent]]


def _sha(text: str | None) -> str:
    return hashlib.sha256((text or "").strip().encode()).hexdigest()


def prompt_hashes(loaded: Agent) -> dict:
    """SHA-256 of the prompts a version resolves to, inherited fields included."""
    return {
        "system_prompt": _sha(loaded.system_prompt),
        "user_prompt": _sha(loaded.user_prompt),
        "signature_prompts": {k: _sha(v) for k, v in sorted(loaded.signature_prompts.items())},
    }


@pytest.mark.parametrize("agent", PAPER_AGENTS)
def test_defaults_use_released_reapo_prompts(registry: CoreAgentRegistry, agent: str) -> None:
    default = _load_prompts(registry, agent, "base")
    released = _load_prompts(registry, agent, "reapo__gpt-5-test")
    assert prompt_hashes(default) == prompt_hashes(released)


def test_agent_without_reapo_keeps_original_defaults(registry: CoreAgentRegistry) -> None:
    default = _load_prompts(registry, "calculator", "base")
    for field in ("system_prompt", "user_prompt"):
        assert (
            getattr(default, field).strip()
            == _expected("calculator", f"core::prompts/{field}.md").strip()
        )


def first_datapoints(loaded: Agent) -> list[str]:
    return [e.name for e in loaded.evaluation_set.evaluations][:3]


@pytest.mark.parametrize(("agent", "version"), LOCK_CASES, ids=[f"{a}:{v}" for a, v in LOCK_CASES])
def test_effective_prompts_match_the_lock(
    registry: CoreAgentRegistry, agent: str, version: str
) -> None:
    """The paper's prompts must not change silently. After an intended change, rewrite the
    lock with ``python tests/test_paper_versions.py``."""
    locked = {k: v for k, v in LOCKED[agent][version].items() if k != "evaluation_set"}
    assert prompt_hashes(_load_prompts(registry, agent, version)) == locked


@pytest.mark.parametrize("agent", PAPER_AGENTS)
def test_every_version_loads_the_locked_eval_sets(registry: CoreAgentRegistry, agent: str) -> None:
    _require_data(agent)
    for version, locked in LOCKED[agent].items():
        loaded = registry.get_agent(agent, version)
        assert first_datapoints(loaded) == locked["evaluation_set"], version


def test_every_version_is_locked() -> None:
    for agent in PAPER_AGENTS:
        assert set(LOCKED[agent]) == {*_versions(agent), "base"}, agent


OPTIMIZER_DIRS = [
    (agent, d.name)
    for agent in PAPER_AGENTS
    for d in sorted((AGENTS / agent / "prompts").iterdir())
    if d.is_dir() and d.name.startswith(("reapo__", "gepa__"))
]


@pytest.mark.parametrize(
    ("agent", "prompt_dir"), OPTIMIZER_DIRS, ids=[f"{a}:{d}" for a, d in OPTIMIZER_DIRS]
)
def test_every_optimizer_prompt_set_has_a_loadable_version(
    registry: CoreAgentRegistry, agent: str, prompt_dir: str
) -> None:
    loaded = _load_prompts(registry, agent, f"{prompt_dir}-test")
    files = {p.read_text().strip() for p in (AGENTS / agent / "prompts" / prompt_dir).glob("*.md")}
    optimized = [*loaded.signature_prompts.values(), loaded.system_prompt]
    assert any(text.strip() in files for text in optimized), "no prompt comes from the set's dir"
    for module, text in loaded.signature_prompts.items():
        assert text.strip() in files, f"{module} not taken from prompts/{prompt_dir}"


def test_claim_history_reapo_user_message(registry: CoreAgentRegistry) -> None:
    """``reapo__gpt-5-test`` sends "Help me with: <inputs JSON>" for each train datapoint."""
    agent = registry.get_agent("claim_history", "reapo__gpt-5-test")
    train = AGENTS / "claim_history" / "evaluations" / "eval-sets"
    train /= "evaluation-set-claim_history_train.json"
    inputs = [dp["inputs"] for dp in json.loads(train.read_text())["evaluations"]]
    assert inputs
    for values in inputs:
        state = agent.input_schema(**values)
        system, human = create_messages(agent, state)
        assert system.content == agent.system_prompt
        assert agent.user_prompt.format_map(state.model_dump()) == human.content
        assert human.content == f"Help me with: {state.model_dump_json()}"


